package com.bluepad.hid

object CompositeReports {
    const val MOUSE_ID = 2
    const val KEYBOARD_ID = 1
    // Put the mouse ID inside its Application collection; retain every existing mouse field.
    val descriptor = MouseReports.descriptor.take(6).toByteArray() + byteArrayOf(0x85.toByte(),MOUSE_ID.toByte()) +
        MouseReports.descriptor.drop(6).toByteArray() + intArrayOf(
            0x05,0x01,0x09,0x06,0xA1,0x01,0x85,KEYBOARD_ID,
            0x05,0x07,0x19,0xE0,0x29,0xE7,0x15,0x00,0x25,0x01,
            0x75,0x01,0x95,0x08,0x81,0x02,
            0x75,0x08,0x95,0x01,0x81,0x03,
            0x05,0x08,0x19,0x01,0x29,0x05,0x75,0x01,0x95,0x05,0x91,0x02,
            0x75,0x03,0x95,0x01,0x91,0x03,
            0x05,0x07,0x19,0x00,0x29,0x73,0x15,0x00,0x25,0x73,
            0x75,0x08,0x95,0x06,0x81,0x00,0xC0
        ).map { it.toByte() }.toByteArray()
    fun input(id: Int, boot: Boolean, mouse: ByteArray, keyboard: ByteArray): ByteArray? = when (id) {
        MOUSE_ID -> MouseReports.forProtocol(mouse,boot)
        KEYBOARD_ID -> keyboard
        else -> null
    }
    fun leds(id: Int, data: ByteArray): Int? = if (id == KEYBOARD_ID && data.size == 1) data[0].toInt() and 31 else null
}
